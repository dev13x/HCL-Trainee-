package day05.generics;

/*
 * Day 05 - Generic key-value holder with two type parameters <K, V>
 */
public class Pair<K, V> {

    private final K key;
    private final V value;

    public Pair(K key, V value) {
        this.key = key;
        this.value = value;
    }

    public K getKey() {
        return key;
    }

    public V getValue() {
        return value;
    }

    @Override
    public String toString() {
        return "(" + key + " : " + value + ")";
    }
}
